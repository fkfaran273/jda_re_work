"""gen_static.py — emit the compiled blocks as ONE static Python module.

vmgen's blocks are exec()d at runtime (so they can be marshalled/cached); for a
native compiler they have to exist as real source.  This writes
vm_blocks_static.py: a single `make(...)` factory holding every block as a
nested `def`, each returning the next pc.  Nuitka/Cython can then compile the
whole interpreter loop into C.
"""
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import vmgen as G                                              # noqa: E402

OUT = os.path.join(HERE, "vm_blocks_static.py")


def main():
    t0 = time.time()
    G.TRACE = False
    t, sig = G.load_tables()
    FAST, PC = t["FAST"], t["PC"]
    bl, srcs, ngen = G.gen_blocks(FAST, PC)
    head = [
        '"""vm_blocks_static.py — GENERATED by gen_static.py. Do not edit."""',
        "",
        "M64 = %d" % G.M64,
        "M32 = %d" % G.M32,
        "M16 = 65535",
        "_rev = lambda a: int.from_bytes((a & 0xFFFFFFFF).to_bytes(4, 'little'), 'big')",
        "",
        "",
        "def make(%s):" % ", ".join(G.FREES),
        "    M64 = %d" % G.M64,
        "    M32 = %d" % G.M32,
        "    M16 = 65535",
        "    _rev = lambda a: int.from_bytes((a & 0xFFFFFFFF).to_bytes(4, 'little'), 'big')",
        "    BPM = {}",
    ]
    body = []
    for n, ((i0, _i1), src) in enumerate(zip(bl, srcs)):
        body.append("")
        body.append("    def b%05d():" % n)
        for ln in src.split("\n"):
            body.append("        " + ln if ln.strip() else "")
        body.append("")
        body.append("    BPM[%d] = b%05d" % (PC[i0], n))
    tail = ["", "    return BPM", ""]
    src_all = "\n".join(head + body + tail)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(src_all)
    print("wrote %s: %d blocks, %.1f MB source, %.1fs"
          % (OUT, len(bl), len(src_all) / 1e6, time.time() - t0))


if __name__ == "__main__":
    main()
