"""spn_law.py — adj7 (Adjust Signature SDK 3.62.0) blob verifier.

Status 2026-10-05:
  * header (16 B)  — CLOSED FORM, verified on both known mints.
      header = 4 u32 words, each = bionic_rand[2i] ^ bionic_rand[2i+1],
      packed big-endian, where the bionic rand stream is seeded with the
      signing second (31-word additive LCG + Schrage MINSTD core, 310
      warm-up draws, output = word >> 1).
  * tag (32 B)     — CLOSED FORM, verified on both known mints.
      tag = HMAC-SHA256(DK37, blob[16:272]).
  * body (256 B)   — NOT YET closed form.  The body is 16 chunks of 16 B
      computed by a 14-round SPN that runs INSIDE the lib's bytecode VM
      (word-stack machine, program generated at run time).  The exact
      round law is still being reverse engineered — see SPN_FINDINGS.md
      and the spn_probe*.py / spn_resume*.py harnesses in this directory.

    python spn_law.py
"""
import hashlib
import hmac
import json
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.abspath(os.path.join(HERE, "..", "..", "adj7_work"))

DK37 = bytes.fromhex("2a4cc07960d647623cc386dcefafbf25"
                     "b669914d32cc8585a1ed7f920ef591eb")

# KB362: the 64-dword whitening key block (LE dword view, unmasked).
# Stored in the lib as immediate runs, duplicated; at run time it is
# materialized into the VM's node heap (heap 0x900a6a8 in the 0015 mint
# holds the contiguous LE copy).
_KB_JSON = os.path.join(WORK, "adj7s4_immruns.json")
KB362_DWORDS = json.load(open(_KB_JSON))["d20a0"]
KB362_LE = b"".join(struct.pack("<I", w) for w in KB362_DWORDS)

_M = (1 << 31) - 1
_A = 16807
_Q = _M // _A
_R = _M % _A


class BionicRand:
    """Android bionic rand(): 31-word additive-feedback LCG over a Schrage
    MINSTD core, 310-draw warm-up, output = state word >> 1."""

    def __init__(self, seed):
        r = self.r = [0] * 31
        s = seed & 0xFFFFFFFF or 1
        w = s if s < 2 ** 31 else s - 2 ** 32
        r[0] = w
        prev = w
        for i in range(1, 31):
            if prev >= 0:
                hi, lo = divmod(prev, _Q)
            else:
                hi = -((-prev) // _Q)
                lo = prev - hi * _Q
            word = _A * lo - _R * hi
            if word < 0:
                word += _M
            prev = word
            r[i] = word
        self.f, self.b = 3, 0
        for _ in range(310):
            self.next()

    def next(self):
        v = (self.r[self.f] + self.r[self.b]) & 0xFFFFFFFF
        self.r[self.f] = v if v < 2 ** 31 else v - 2 ** 32
        o = v >> 1
        self.f = (self.f + 1) % 31
        self.b = (self.b + 1) % 31
        return o


def make_header(unix_sec):
    """16-B header: 8 bionic draws pair-XORed, packed big-endian."""
    R = BionicRand(unix_sec)
    d = [R.next() for _ in range(8)]
    w = [d[2 * i] ^ d[2 * i + 1] for i in range(4)]
    return b"".join(v.to_bytes(4, "big") for v in w)


def verify_tag(blob):
    return hmac.new(DK37, blob[16:272], hashlib.sha256).digest() \
        == blob[272:304]


KNOWN_MINTS = [
    # (label, sec, sid, blob-source)
    ("v3", 1771238644, "0015", os.path.join(HERE, "v3_blob.hex")),
    ("adj7s4", 1789382946, "0001",
     os.path.join(WORK, "adj7s4_out7.json")),
]


def load_blob(entry):
    label, sec, sid, path = entry
    if path.endswith(".hex"):
        return bytes.fromhex(open(path).read().strip())
    return bytes.fromhex(json.load(open(path))["out_hex"])


def main():
    ok_all = True
    for entry in KNOWN_MINTS:
        label, sec, sid, _ = entry
        blob = load_blob(entry)
        hdr = make_header(sec)
        hdr_ok = hdr == blob[:16]
        tag_ok = verify_tag(blob)
        print("%-8s sec=%d sid=%s len=%d" % (label, sec, sid, len(blob)))
        print("  header: expected %s" % hdr.hex())
        print("          actual   %s  -> %s" % (blob[:16].hex(),
                                                "OK" if hdr_ok else "FAIL"))
        print("  tag   : -> %s" % ("OK" if tag_ok else "FAIL"))
        ok_all &= hdr_ok and tag_ok
    print()
    print("header+tag closed-form laws:",
          "ALL OK" if ok_all else "FAILURES PRESENT")
    print("body: 256 B = 16 SPN chunks -- closed form still open")
    print("       (see SPN_FINDINGS.md; the SPN is a 14-round structure")
    print("       inside the run-time-generated bytecode VM program)")


if __name__ == "__main__":
    main()
