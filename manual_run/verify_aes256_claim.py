def part2_schedule():
    print()
    print("=" * 70)
    print("PART 2  is KB the AES-256 key expansion of KB[0:32]?")
    print("=" * 70)
    kb = P.KB
    rk = aes256_expand(kb[0:32])
    first_bad = None
    for i in range(15):
        got = bytes(rk[i])
        want = kb[16 * i:16 * i + 16]
        if got != want:
            first_bad = i
            print("   round %2d  MISMATCH" % i)
            print("      expansion gives %s" % got.hex())
            print("      KB has        %s" % want.hex())
            break
    if first_bad is None:
        print("   all 15 round keys match -- KB IS an AES-256 expansion.")
        return True
    else:
        print("   -> KB is NOT the standard AES-256 expansion.")
        return False


