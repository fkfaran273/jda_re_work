RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]


def aes256_expand(key32):
    """The standard AES-256 key schedule -> 15 round keys of 16 bytes."""
    # AES-256 has Nk = 8 words = two 16-byte round keys, so the
    # recurrence strides by TWO round keys, not eight.
    rk = [bytearray(key32[0:16]), bytearray(key32[16:32])]
    for i in range(2, 15):
        t = bytearray(rk[i - 1])
        if i % 8 == 0:
            t = t[1:] + t[:1]                       # RotWord
            t = bytearray(SB[b] for b in t)           # SubWord
            t[0] ^= RCON[i // 8]
        elif i % 8 == 4:
            t = bytearray(SB[b] for b in t)           # SubWord
        rk.append(bytearray(a ^ b for a, b in zip(rk[i - 2], t)))
    return rk


