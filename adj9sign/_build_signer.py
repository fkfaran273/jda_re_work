"""_build_signer.py — generates adj9_signer.py, the single-file adj9 signer.

Stitches the proven signing stack into ONE self-contained file:
  header_gen  (16-B header, bionic rand pair-XOR)
  F.py        (region materializer: d0/d2/d4 from the 32-B seed S)
  desc10_law  (claims serialization, byte-exact session/click, predicted
               attribution)
  vm_final    (the FinEx ARM64 VM interpreter; runtime part)
  fin_vm2     (FinEx wrapper: streams, emit trace)
  mint API    (VA_ORDER, claims_for_law, finex_mint, auth_header)

The VM disassembles libsigner.so at import; the three code spans it reads are
embedded here as base64, so adj9_signer.py needs no files beside it (only the
capstone pip package).

Run:  python _build_signer.py
"""
import base64
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REV = os.path.join(os.path.dirname(HERE), "adj9", "rev")
LIB = os.path.join(os.path.dirname(HERE), "extracted", "arm64", "lib",
                   "arm64-v8a", "libsigner.so")
# the exact byte ranges vm_final disassembles (vaddr == file offset here)
SPANS = [(0x99000, 0xBCA30), (0x100094, 0x12AA48), (0x146000, 0x149000)]


def read(name):
    return open(os.path.join(REV, name), encoding="utf-8").read()


def block(text, start, end=None):
    i = text.index(start)
    if end is None:
        return text[i:]
    j = text.index(end, i)
    return text[i:j]


# ---------------------------------------------------------------- spans ---
lib = open(LIB, "rb").read()
span_lines = []
for a, b in SPANS:
    b64 = base64.b64encode(lib[a:b]).decode()
    span_lines.append("    (0x%05X, 0x%05X,\n     \"%s\")," % (a, b, b64))
SPANS_SRC = "\n".join(span_lines)

# ------------------------------------------------------- source pieces ---
hg = read("header_gen.py")
hg = block(hg, "# header_gen.py", "\nif __name__")

Fsrc = read("F.py")
Fsrc = Fsrc.replace("from __future__ import annotations\n", "")
Fsrc = block(Fsrc, "_MASK31 = 0x7FFFFFFF", "\nif __name__")

dl = read("desc10_law.py")
dl = block(dl, "PROFILE_COMMON", "\ndef self_test")

vm = read("vm_final.py")
vm_rt = block(vm, "OP_PUSH, OP_POP, OP_EMIT, OP_LENQ, OP_OUTLEN")
vm_rt = vm_rt[:vm_rt.index('\nif __name__ == "__main__"')]

fv = read("fin_vm2.py")
fv_rt = block(fv, "OP_PUSH, OP_POP = 0x147630")
fv_rt = fv_rt.replace("class FinEx(V.Ex):", "class FinEx(Ex):")
if "\nif __name__" in fv_rt:
    fv_rt = fv_rt[:fv_rt.index("\nif __name__")]

mp = read("mint_pipeline.py")
mint_const = "\n".join(l for l in mp.splitlines()
                       if re.match(r"^(VA_ORDER|SINK|BLOB_WORDS|ADJ_VERIFICATION|"
                                   r"ADJ_SIGNING_ID|CLIENT_SDK|NATIVE_VERSION) ", l))
mint_api = "\n".join([
    block(mp, "def claims_for_law", "\ndef build_descriptors"),
    block(mp, "def finex_mint", "\ndef mint_blob_ex"),
    block(mp, "def auth_header", "\ndef region_laws"),
])

# ------------------------------------------------------------ emission ---
out = '''"""adj9_signer.py — SELF-CONTAINED adj9 signature minting.

Auto-generated by _build_signer.py; do not edit by hand.

Public API:
  make_header(unix_sec)                     -> 16-byte header
  F.region(S, pid=0, tid=0, head=None)      -> (d0[36], d2, d4[8]) words
  desc10_keys(kind, val) / build_desc10(v,k)-> the claims law
  claims_for_law(val, kind)                 -> (padded #10 bytes, unpadded len)
  build_descriptors-like assembly           -> do it via VA_ORDER (see below)
  finex_mint(descs, second)                 -> (192-B blob, info)
  auth_header(blob)                         -> Authorization header value

Descriptor order (VA_ORDER): [0, 9, 8, 4, 2, 7, 10, 5, 1, 6, 3]
  #0 d0 (36 w) | #9 D9 | #8 D8 | #4 d4 (8 w) | #2 d2 (1 w)
  #7 unpadded claims len | #10 padded claims | #5 0 | #6 0 | #1 [] | #3 []

Deps: capstone (pip install capstone). No files needed beside this module.
"""
from __future__ import annotations
import base64 as _b64
import base64
import re
import struct
import sys

# ==================================================================
# 1. embedded libsigner.so code spans (vaddr-indexed, base64)
# ==================================================================
_SPANS = [
%(SPANS)s
]


class _LibBytes:
    """vaddr-indexed sparse view of the disassembled code ranges."""

    def __init__(self, spans):
        self._spans = sorted((a, b, _b64.b64decode(s)) for a, b, s in spans)

    def __getitem__(self, sl):
        if not isinstance(sl, slice) or sl.step is not None:
            raise TypeError("vaddr slicing only")
        out = bytearray()
        for a, b, raw in self._spans:
            lo, hi = max(a, sl.start), min(b, sl.stop)
            if hi > lo:
                out += raw[lo - a:hi - a]
        if len(out) != sl.stop - sl.start:
            raise KeyError("vaddr range %%s not fully embedded" %% (sl,))
        return bytes(out)


# ==================================================================
# 2. VM setup (replaces vm_final.py's import-time disassembly)
# ==================================================================
elf = _LibBytes(_SPANS)
from capstone import Cs, CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN

md = Cs(CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN)
md.detail = True
INS = list(md.disasm(elf[0x100094:0x12aa48], 0x100094))
IDX = {i.address: k for k, i in enumerate(INS)}
# second executable range: output assembly fn (slice 17/33), vaddr==offset
_INS0 = list(md.disasm(elf[0x99000:0xBB548], 0x99000))
_b = len(INS)
INS.extend(_INS0)
for _k, _i in enumerate(_INS0):
    IDX[_i.address] = _b + _k
_INS3 = list(md.disasm(elf[0x146000:0x149000], 0x146000))
_b = len(INS)
INS.extend(_INS3)
for _k, _i in enumerate(_INS3):
    IDX[_i.address] = _b + _k
_INS2 = list(md.disasm(elf[0xBB548:0xBCA30], 0xBB548))
_b = len(INS)
INS.extend(_INS2)
for _k, _i in enumerate(_INS2):
    IDX[_i.address] = _b + _k

FAST = [(i.mnemonic, i.op_str, i.address + 4) for i in INS]
m0 = [i.mnemonic for i in INS]

# ==================================================================
# 3. header law (bionic rand pair-XOR, 36/36 corpus)
# ==================================================================
%(HG)s

# ==================================================================
# 4. region materializer (F.py: d0/d2/d4 from the 32-B seed S)
# ==================================================================
%(F)s

# ==================================================================
# 5. claims law (desc10: byte-exact session 360 B / click 388 B,
#    attribution predicted)
# ==================================================================
%(DL)s

# ==================================================================
# 6. FinEx VM interpreter (vm_final.py runtime)
# ==================================================================
%(VM)s

# ==================================================================
# 7. FinEx stream wrapper (fin_vm2.py runtime)
# ==================================================================
%(FV)s

# ==================================================================
# 8. mint API (mint_pipeline.py essentials)
# ==================================================================
%(MC)s

%(MA)s
''' % {"SPANS": SPANS_SRC, "HG": hg, "F": Fsrc, "DL": dl, "VM": vm_rt,
       "FV": fv_rt, "MC": mint_const, "MA": mint_api}

path = os.path.join(HERE, "adj9_signer.py")
open(path, "w", encoding="utf-8", newline="\n").write(out)
print("wrote %s (%d KB)" % (path, len(out) // 1024))
print("spans embedded: %d bytes of libsigner.so" % sum(b - a for a, b in SPANS))
